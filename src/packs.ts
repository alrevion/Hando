const BY_ID = new Map(PACKS.map((p) => [p.id, p]));

/** Профиль по идентификатору. Неизвестный -- «Другое», а не падение. */
export function pack(id: string | null | undefined): Pack {
  return (id && BY_ID.get(id)) || BY_ID.get('generic')!;
}

/**
 * Подпись кнопки профиля. Одна функция на экран и на разбор нажатия: подпись
 * reply-кнопки -- это то, что бот получит обратно текстом, и собранная в двух
 * местах она однажды разойдётся.
 */
export function packButton(p: Pack): string {
  return `${p.emoji} ${p.title}`;
}

/** Профиль по подписи нажатой кнопки. */
export function packByButton(text: string): Pack | undefined {
  return PACKS.find((p) => packButton(p) === text);
}
