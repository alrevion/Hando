const CAT_BY_ID = new Map(CATEGORIES.map((c) => [c.id, c]));
const IND_BY_ID = new Map(INDUSTRIES.map((i) => [i.id, i]));

/** Категория и отрасль, сложенные вместе. Кэш: складывать на каждый разбор незачем. */
const MERGED = new Map<string, Pack>();

function merge(ind: Industry): Pack {
  const cat = CAT_BY_ID.get(ind.category) ?? CAT_BY_ID.get('other')!;
  const both = (a?: string[], b?: string[]) => [...(a ?? []), ...(b ?? [])];
  return {
    id: ind.id,
    title: ind.title,
    emoji: cat.emoji,
    category: cat.id,
    categoryTitle: cat.title,
    departments: ind.departments,
    // Свои должности идут первыми: они точнее общих по категории.
    positions: [...new Set(both(ind.positions, cat.positions))],
    urgent: both(cat.urgent, ind.urgent),
    low: both(cat.low, ind.low),
    ack: both(cat.ack, ind.ack),
    examples: ind.examples?.length ? ind.examples : (cat.examples ?? []),
  };
}

/** Профиль по идентификатору. Неизвестный -- «Другое», а не падение. */
export function pack(id: string | null | undefined): Pack {
  const ind = (id && IND_BY_ID.get(id)) || IND_BY_ID.get('generic')!;
  let m = MERGED.get(ind.id);
  if (!m) {
    m = merge(ind);
    MERGED.set(ind.id, m);
  }
  return m;
}

/** Все профили одним списком -- для приложения и для проверок. */
export const PACKS: Pack[] = INDUSTRIES.map((i) => pack(i.id));

/** Отрасли одной категории. */
export function packsOf(categoryId: string): Pack[] {
  return PACKS.filter((p) => p.category === categoryId);
}

/**
 * Подписи кнопок. Одна функция на экран и на разбор нажатия: подпись
 * reply-кнопки -- это то, что бот получит обратно текстом, и собранная в двух
 * местах она однажды разойдётся.
 */
export function categoryButton(c: Category): string {
  return `${c.emoji} ${c.title}`;
}
export function packButton(p: Pack): string {
  return p.title;
}

export function categoryByButton(text: string): Category | undefined {
  return CATEGORIES.find((c) => categoryButton(c) === text);
}
export function packByButton(text: string): Pack | undefined {
  return PACKS.find((p) => packButton(p) === text);
}
