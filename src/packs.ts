// Отраслевые профили организации.
//
// Профиль -- это не ярлык на карточке, а три вещи, которые действительно
// меняются от отрасли к отрасли:
//
//   1. ОТДЕЛЫ. Раз доска = отдел, набор досок и есть структура организации.
//      Школе нужны «Учебная часть» и «Классные руководители», стройке --
//      «Объекты» и «Снабжение». Одна доска «Задачи» не годится ни той, ни другой.
//
//   2. СЛОВА СРОЧНОСТИ. Универсальное «срочно» знают все, но настоящий сигнал
//      тревоги в каждой отрасли свой и слова «срочно» в себе не содержит:
//      на стройке это «простой» и «бетон едет», в цеху -- «линия стоит», в
//      клинике -- «пациент ждёт», в общепите -- «стоп-лист». Разбор обязан их
//      понимать, иначе самая горящая фраза получает среднюю срочность.
//
//   3. СЛОВА ОЗНАКОМЛЕНИЯ. Рассылка «прочитать и принять к сведению» в школе
//      называется приказом, на стройке -- инструктажем по ТБ, в цеху --
//      техкартой. Все они означают одно: отчитываться о работе не нужно.
//
// Должности лежат здесь же -- их будет предлагать кнопками подтверждение
// заявки (раздел 15 концепции). Пока не используются НИГДЕ: это данные под
// решённую, но не сделанную вещь, и когда она появится, словарь уже готов.
//
// Строки в urgent/low/ack -- ФРАГМЕНТЫ РЕГУЛЯРОК, а не буквальные слова:
// склонения задаются классом [а-яё]*, как в базовом словаре parse.ts.
// Границы слова навешивает parse.ts своей функцией word(), поэтому «ср» внутри
// «срочно» и подобные ловушки закрыты там же, один раз для всех.

export type Pack = {
  id: string;
  title: string;
  emoji: string;
  /** Доски, которые заводятся вместе с организацией. Первая -- основная. */
  departments: string[];
  /** Должности для подтверждения заявки. Ждут раздела 15. */
  positions: string[];
  /** Что в этой отрасли значит «горит». */
  urgent?: string[];
  /** Что значит «не горит». */
  low?: string[];
  /** Что значит «прочитать и принять к сведению». */
  ack?: string[];
  /** Подсказки в пустом экране и при создании: что сюда вообще писать. */
  examples: string[];
};

