-- Две вещи, которых не хватало по просьбе владельца.
--
-- repeat_days: «поливать цветы через день» -- не задача, которую однажды
-- выполняют и закрывают. Она возвращается. Число дней, а не расписание cron:
-- «через день» это 2, «каждую неделю» 7, и этого хватает всему, что люди
-- диктуют вслух. Следующий заход заводится при ПОДТВЕРЖДЕНИИ предыдущего, а не
-- по часам: иначе невыполненная задача плодила бы копии сама себя.
--
-- checklist: «купить свёклу, морковь, молоко» -- одна задача с несколькими
-- пунктами, а не три задачи и не одна неделимая. JSON-массив
-- [{"t":"молоко","d":null}] прямо в строке задачи: отдельная таблица дала бы
-- ещё один запрос на каждую карточку списка ради данных, которые всегда
-- читаются целиком вместе с задачей.
ALTER TABLE tasks ADD COLUMN repeat_days INTEGER;
ALTER TABLE tasks ADD COLUMN checklist TEXT;
ALTER TABLE drafts ADD COLUMN repeat_days INTEGER;
ALTER TABLE drafts ADD COLUMN checklist TEXT;
