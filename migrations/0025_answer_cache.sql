-- Память ответов помощника: вопрос -> готовый ответ, по СМЫСЛУ, а не по буквам.
--
-- Сюда попадают ТОЛЬКО ответы про то, как устроен Hando: «как отметить
-- выполненную», «кому видно мои задачи». Они одинаковы для всех, поэтому
-- таблица общая. Ответы, которые опираются на задачи конкретного человека,
-- сюда не попадают никогда -- проверяется дважды: модель помечает ответ общим,
-- и код отдельно смотрит, не просочились ли в него названия задач и имена.
--
-- Замер на живых фразах (11 сентября, MiniLM на Ampere): перефраз вопроса по
-- руководству даёт 0.93, разные вопросы -- 0.40-0.56. Отсюда и порог 0.90.
-- Для поручений эта затея не годится вовсе: подмена срока даёт 0.95, то есть
-- «та же задача с другим сроком» неотличима от «той же задачи».
CREATE TABLE answer_cache (
  id TEXT PRIMARY KEY,
  -- 384 числа float32 -- 1536 байт. Поиск идёт в Worker: строк тут десятки,
  -- и отдельная векторная база на такой объём -- лишний сервис.
  vector BLOB NOT NULL,
  answer TEXT NOT NULL,
  -- Чем посчитан вектор. Сменим модель -- старые строки просто перестанут
  -- подходить, а не начнут врать: размерность и пространство у моделей разные.
  model TEXT NOT NULL,
  hits INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
