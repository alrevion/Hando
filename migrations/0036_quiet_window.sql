-- Тихие часы -- настройка пространства, а не константа.
--
-- Раньше ночной пол был 20:00-08:00 и только у пространств с графиком; у 24/7
-- (семья, личное) тишины не было вовсе, а «Просрочено» повторялось каждый
-- час без предела: по двум задачам у одного человека -- 276 сообщений за
-- пять дней, 118 из них ночью. Теперь окно у каждого пространства своё,
-- по умолчанию 22:00-08:00; одинаковые «с» и «до» -- тишины нет.
ALTER TABLE orgs ADD COLUMN quiet_from TEXT NOT NULL DEFAULT '22:00';
ALTER TABLE orgs ADD COLUMN quiet_to TEXT NOT NULL DEFAULT '08:00';

-- Сколько раз уже напомнили: «Просрочено» и «Не принято» -- три раза раз в
-- час, дальше раз в день утром. Кому уже напоминали много раз, тот сразу
-- переходит на «раз в день».
ALTER TABLE reminders ADD COLUMN n INTEGER NOT NULL DEFAULT 1;
UPDATE reminders SET n = 3 WHERE kind IN ('overdue', 'not_accepted');
