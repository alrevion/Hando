-- Вход в браузере через бота. Вход по телефону шёл через внешний сервис
-- кодов, который у Hando не подключён: из браузера войти было нельзя вовсе.
--
-- Сайт заводит одноразовый ключ и кладёт его в свою куку, человек
-- подтверждает вход в @hando_ai_bot, сайт по куке забирает сессию. Строка
-- живёт минуты и удаляется при входе.
CREATE TABLE login_links (
  token TEXT PRIMARY KEY,
  user_id TEXT REFERENCES users(id),
  created_at TEXT NOT NULL,
  confirmed_at TEXT
);
