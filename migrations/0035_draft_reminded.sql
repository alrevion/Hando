-- Утренняя сводка напоминает о неподтверждённом черновике ОДИН раз.
-- Раньше карточка приходила заново каждое утро, без объяснения и рядом со
-- старой -- человек не понимал, откуда «новый» черновик.
ALTER TABLE drafts ADD COLUMN reminded_at TEXT;

-- Черновики старше сегодняшнего дня сводка уже присылала (до этой миграции --
-- каждое утро). Ещё одного раза им не нужно.
UPDATE drafts SET reminded_at = datetime('now') WHERE created_at < date('now');
