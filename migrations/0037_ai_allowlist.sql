-- Нейросети (Groq: разбор фраз, ассистент, расшифровка голоса) -- только тем,
-- кому включено. Репозиторий открыт, регистрация тоже: без этого любой
-- новый человек тратил бы общий лимит Groq. Все, кто есть на момент
-- миграции, остаются с нейросетями; новые -- без них (разбор по шаблонам),
-- пока владелец не включит: UPDATE users SET ai_enabled = 1 WHERE id = ?.
ALTER TABLE users ADD COLUMN ai_enabled INTEGER NOT NULL DEFAULT 0;
UPDATE users SET ai_enabled = 1;
