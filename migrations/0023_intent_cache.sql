-- Память разбора намерения (шаг «не звать модель дважды на одно и то же»).
--
-- Хранится ОТПЕЧАТОК фразы, а не фраза: судить «вопрос это или поручение» --
-- свойство языка, а не организации, поэтому таблица общая, и общей она может
-- быть только без текста. Восстановить фразу по отпечатку нельзя, значит
-- заголовки чужих поручений через эту таблицу не утекают.
--
-- Строки не протухают: язык не меняется. Если поменяется САМ разборщик --
-- таблицу чистят целиком, это дешевле версионирования.
CREATE TABLE intent_cache (
  phrase TEXT PRIMARY KEY,
  intent TEXT NOT NULL CHECK (intent IN ('ask','task')),
  -- Сколько раз ответ взяли из памяти. Единственное свидетельство, что слой
  -- окупается: без счётчика о нём нечего сказать, кроме «он есть».
  hits INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);
