-- Кнопочное меню бота: состояние диалога и мягкое удаление организации.

-- Что бот ждёт от человека следующим сообщением. JSON вида {"await":"new"} или
-- {"await":"ren","org":"..."}.
--
-- Состояние на пользователе, а не в отдельной таблице: оно короткоживущее (один
-- шаг диалога), принадлежит ровно одному человеку и умирает вместе с ним.
-- Отдельная таблица потребовала бы своей уборки просроченных строк.
ALTER TABLE users ADD COLUMN bot_state TEXT;

-- Сообщение с меню: правим его на месте, а не шлём новое на каждое нажатие.
-- Иначе чат за минуту превращается в ленту одинаковых меню.
ALTER TABLE users ADD COLUMN menu_message_id TEXT;

-- Мягкое удаление организации. Жёсткое невозможно: на orgs ссылаются задачи,
-- события, вложения и членства -- всё, что составляет историю работы. Владелец
-- убирает организацию из своего списка, а не стирает чужой труд.
ALTER TABLE orgs ADD COLUMN archived_at TEXT;
