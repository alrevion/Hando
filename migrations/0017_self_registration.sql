-- Авторегистрация: человек заводит себя сам, без ручного ввода директором.
--
-- Модель владельца (2026-09-06): человек подключает бота и дальше либо СОЗДАЁТ
-- свою организацию (тогда он её владелец и плательщик), либо ВСТУПАЕТ по коду в
-- чужую -- и там его подтверждает тот, кто код выдал. Директор платит за всю
-- свою организацию; кто зарегистрировался сам, платит только за свои.

-- Код вступления в организацию. Многоразовый, в отличие от одноразовой ссылки:
-- его раздают в общем чате, поэтому сам по себе он доступа НЕ даёт -- только
-- заявку, которую подтверждают. Ротируется владельцем.
ALTER TABLE orgs ADD COLUMN join_code TEXT;
CREATE UNIQUE INDEX idx_orgs_join_code ON orgs(join_code);

-- Кто платит за организацию. Роль creator уже указывает на владельца, но роль --
-- это про права, а плательщик -- про деньги, и однажды они разойдутся (владелец
-- ушёл, права передали). Отдельное поле дешевле сейчас, чем разбор потом.
ALTER TABLE orgs ADD COLUMN owner_user_id TEXT REFERENCES users(id);

-- Заявка на вступление: членство создано, но доступа ещё НЕТ.
-- NULL = ждёт подтверждения. Все проверки членства (membershipRole,
-- resolveOrgId, org-предикаты) обязаны требовать НЕ NULL -- иначе вступивший по
-- коду получал бы доступ мгновенно, и подтверждение было бы декорацией.
--
-- Отдельная колонка, а не значение в role: роль у заявки уже известна (её
-- выбирает подтверждающий), и смешивать «кто он» с «пустили ли его» -- значит
-- получить роль, которая иногда означает отсутствие прав.
ALTER TABLE org_memberships ADD COLUMN confirmed_at TEXT;

-- Существующие членства созданы до появления заявок -- они подтверждены.
UPDATE org_memberships SET confirmed_at = created_at WHERE confirmed_at IS NULL;

-- Владелец пилотной организации -- её creator, если он есть.
UPDATE orgs SET owner_user_id = (
  SELECT m.user_id FROM org_memberships m
   WHERE m.org_id = orgs.id AND m.role = 'creator' AND m.left_at IS NULL LIMIT 1
) WHERE owner_user_id IS NULL;

-- Незавершённая регистрация: человек подключил бота, но организации у него ещё
-- нет. Раньше такого состояния не существовало -- users создавались только
-- директором и сразу с членством.
CREATE INDEX idx_users_pending_signup ON users(telegram_user_id) WHERE current_org_id IS NULL;
